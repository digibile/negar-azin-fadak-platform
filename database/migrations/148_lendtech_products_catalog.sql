-- 148: canonical lendtech product catalogue with explicit legacy provenance and review gate.
create table if not exists lendtech_products (
  id uuid primary key default gen_random_uuid(),
  tenant_ref text not null,
  product_code text not null,
  slug text not null,
  name text not null,
  title text not null default '',
  description text not null default '',
  badge text not null default '',
  min_amount numeric(20,2) not null default 0 check(min_amount>=0),
  max_amount numeric(20,2) not null default 0 check(max_amount>=min_amount),
  interval_days integer not null default 0 check(interval_days>=0),
  tiers jsonb not null default '[]'::jsonb,
  conditions jsonb not null default '{}'::jsonb,
  documents jsonb not null default '[]'::jsonb,
  image_url text not null default '',
  full_description_html text not null default '',
  source_is_active boolean not null default false,
  is_active boolean not null default false,
  show_in_list boolean not null default false,
  send_reminders boolean not null default false,
  sort_order integer not null default 0,
  interest_method text not null default 'Monthly' check(interest_method in ('Monthly','Annual','Flat')),
  interest_percent numeric(12,6) not null default 0,
  late_daily_coef numeric(16,8) not null default 0,
  early_daily_coef numeric(16,8) not null default 0,
  labels jsonb not null default '[]'::jsonb,
  operational_costs jsonb not null default '[]'::jsonb,
  needs_review boolean not null default true,
  status text not null default 'draft' check(status in ('draft','approved','published','archived')),
  reviewed_by text,
  reviewed_at timestamptz,
  review_note text not null default '',
  published_by text,
  published_at timestamptz,
  legacy_source_database text,
  legacy_source_table text,
  legacy_id text,
  legacy_payload jsonb not null default '{}'::jsonb,
  created_by text not null default 'system',
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique(tenant_ref,product_code),
  unique(tenant_ref,legacy_source_table,legacy_id)
);
create index if not exists idx_lendtech_products_public
  on lendtech_products(tenant_ref,status,is_active,show_in_list,sort_order);
create index if not exists idx_lendtech_products_review
  on lendtech_products(tenant_ref,needs_review,status,created_at);
